// Three fields only — school, programme, intake year — prefilled from the
// student's profile. Deadlines/requirements come from the generated plan,
// not manual entry.

function AddForm({ defaults, onAdd, onCancel }: {
  defaults: ProfileDefaults
  onAdd: (u: UniversityTarget) => void
  onCancel: () => void
}) {
  const currentYear = new Date().getFullYear()
  const [uniName, setUniName] = useState(defaults.university)
  const [programme, setProg]  = useState(defaults.programme)
  const [year, setYear]       = useState(defaults.enrollmentYear ?? currentYear + 1)
  const [phase, setPhase]     = useState<'idle' | 'saving' | 'planning'>('idle')
  const supabase = createBrowserClient()
  const toast = useToast()
  const locale = useLocale()
  const t = T[locale]

  const prefilled = Boolean(defaults.university || defaults.programme)
  const years = Array.from({ length: 7 }, (_, i) => currentYear + i)

  async function submit(e: React.FormEvent) {
    e.preventDefault()
    if (!uniName.trim() || phase !== 'idle') return
    setPhase('saving')
    const { data, error } = await supabase
      .from('university_targets')
      .insert({
        name: uniName.trim(),
        programme: programme.trim(),
        country: '',
        requirements: '',
        notes: '',
        reference_link: '',
        status: 'researching',
      })
      .select('id')
      .single()
    if (error || !data) {
      setPhase('idle')
      toast({ title: t.addFailed, variant: 'error' })
      return
    }

    // Generate the plan immediately — this is the assistant's whole point.
    setPhase('planning')
    let plan: ApplicationPlan | null = null
    let planUpdatedAt: string | null = null
    try {
      const res = await fetch('/api/universities/plan', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ targetId: data.id }),
      })
      if (res.ok) {
        const json = await res.json()
        plan = json.plan
        planUpdatedAt = json.planUpdatedAt
      }
    } catch { /* plan can be regenerated from the card */ }

    onAdd({
      id: data.id,
      name: uniName.trim(),
      country: '',
      programme: programme.trim(),
      deadline: null,
      requirements: '',
      notes: '',
      status: 'researching',
      referenceLink: '',
      applicationPlan: plan,
      planUpdatedAt,
    })
    if (!plan) toast({ title: t.addedPlanFailed, description: t.addedPlanFailedDesc, variant: 'error' })
  }

  const cls = "w-full px-3 py-2.5 border border-[var(--border)] rounded-[8px] text-[13px] bg-white text-[var(--t900)] focus:outline-none focus:border-[var(--blue)] placeholder:text-[var(--t300)]"

  return (
    <form onSubmit={submit} className="bg-[var(--blue-50)] border border-[var(--blue-100)] rounded-[12px] p-5 mb-5 flex flex-col gap-3">
      <div className="font-display font-bold text-[13px] text-[var(--blue)]">{t.addTitle}</div>
      {prefilled && (
        <div className="text-[11px] text-[var(--t500)]">{t.prefilledHint}</div>
      )}
      <div className="grid grid-cols-1 sm:grid-cols-3 gap-3">
        <div>
          <label className="block text-[11px] font-semibold text-[var(--t700)] mb-1">{t.universityLabel}</label>
          <input value={uniName} onChange={e => setUniName(e.target.value)} placeholder={t.universityPh} className={cls} required />
        </div>
        <div>
          <label className="block text-[11px] font-semibold text-[var(--t700)] mb-1">{t.programmeLabel}</label>
          <input value={programme} onChange={e => setProg(e.target.value)} placeholder={t.programmePh} className={cls} />
        </div>
        <div>
          <label className="block text-[11px] font-semibold text-[var(--t700)] mb-1">{t.intakeYear}</label>
          <select value={year} onChange={e => setYear(Number(e.target.value))} className={cls}>
            {years.map(y => <option key={y} value={y}>{y}</option>)}
          </select>
        </div>
      </div>
      <div className="flex items-center justify-between pt-1">
        <div className="text-[11px] text-[var(--t400)]">
          {t.autoGenerated}{' '}
          {phase === 'planning' && <span className="font-semibold text-[var(--blue)]">{t.generating}</span>}
        </div>
        <div className="flex gap-2">
          <button type="button" onClick={onCancel} className="px-4 py-2 rounded-[7px] text-[12px] font-semibold text-[var(--t500)] hover:bg-white transition">{t.cancel}</button>
          <button type="submit" disabled={phase !== 'idle'} className="px-4 py-2 rounded-[7px] text-[12px] font-semibold bg-[var(--blue)] text-white hover:bg-[var(--blue-h)] disabled:opacity-50 transition">
            {phase === 'saving' ? t.adding : phase === 'planning' ? t.buildingPlan : t.addAndBuild}
          </button>
        </div>
      </div>
    </form>
  )
}

