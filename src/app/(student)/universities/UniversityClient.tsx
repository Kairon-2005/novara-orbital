type Dict = (typeof T)[keyof typeof T]

const COUNTRY_EMOJI: Record<string, string> = {
  'UK': '🇬🇧', 'United Kingdom': '🇬🇧',
  'US': '🇺🇸', 'USA': '🇺🇸', 'United States': '🇺🇸',
  'Singapore': '🇸🇬', 'SG': '🇸🇬',
  'Australia': '🇦🇺', 'AU': '🇦🇺',
  'Canada': '🇨🇦', 'CA': '🇨🇦',
  'Netherlands': '🇳🇱', 'Germany': '🇩🇪',
  'Hong Kong': '🇭🇰', 'Japan': '🇯🇵',
}

function countryFlag(country: string) {
  return COUNTRY_EMOJI[country] ?? '🌏'
}

function daysUntil(dateStr: string | null, t: Dict): { text: string; urgent: boolean } {
  if (!dateStr) return { text: t.noDeadline, urgent: false }
  const diff = Math.ceil((new Date(dateStr).getTime() - Date.now()) / 86400000)
  if (diff < 0)   return { text: t.deadlinePassed, urgent: true }
  if (diff === 0) return { text: t.dueToday, urgent: true }
  if (diff <= 30) return { text: t.daysLeft(diff), urgent: true }
  if (diff <= 90) return { text: t.daysLeft(diff), urgent: false }
  return { text: t.daysLeft(diff), urgent: false }
}

